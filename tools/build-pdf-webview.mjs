#!/usr/bin/env node
/**
 * Builds assets/pdfjs/pdf-reader.html: the on-device PDF text reader (owner decision D-A1,
 * 2026-10-03). One self-contained offline page:
 *   - pdf.js (pdfjs-dist legacy build, Apache-2.0) and its worker, embedded as strings and
 *     loaded from blob: URLs — nothing is fetched;
 *   - the SAME page logic as the worker-host reader (tools/pdf-pages.mjs);
 *   - a Content-Security-Policy with no network access at all (connect-src limited to blob:/data:),
 *     so a document's content can never leave the device from this page.
 *
 * Usage: node tools/build-pdf-webview.mjs   (re-run after upgrading pdfjs-dist)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('pdfjs-dist/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const lib = readFileSync(join(pkgDir, 'legacy', 'build', 'pdf.min.mjs'), 'utf8');
const worker = readFileSync(join(pkgDir, 'legacy', 'build', 'pdf.worker.min.mjs'), 'utf8');
const pages = readFileSync(join(ROOT, 'tools', 'pdf-pages.mjs'), 'utf8').replace(
  /^export async function readPdfPages/m,
  'async function readPdfPages',
);

/** A JS string literal that is safe inside an inline <script>. */
const literal = (s) =>
  JSON.stringify(s)
    .replace(/</g, '\\u003c')
    .replace(new RegExp(String.fromCharCode(0x2028), 'g'), '\\u2028')
    .replace(new RegExp(String.fromCharCode(0x2029), 'g'), '\\u2029');

const MAX_PAGES = 300;

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:; worker-src blob:; connect-src blob: data:">
<!-- GENERATED by tools/build-pdf-webview.mjs — do not edit by hand.
     Contains pdf.js ${version} (pdfjs-dist, Apache License 2.0, https://github.com/mozilla/pdf.js). -->
</head>
<body>
<script>
"use strict";
var PDFJS_SRC = ${literal(lib)};
var WORKER_SRC = ${literal(worker)};
${pages}
var chunks = {};
var libPromise = null;
function pdfLib() {
  if (!libPromise) {
    libPromise = import(URL.createObjectURL(new Blob([PDFJS_SRC], { type: 'text/javascript' }))).then(
      function (m) {
        m.GlobalWorkerOptions.workerSrc = URL.createObjectURL(
          new Blob([WORKER_SRC], { type: 'text/javascript' }),
        );
        return m;
      },
    );
  }
  return libPromise;
}
function post(message) {
  window.ReactNativeWebView.postMessage(JSON.stringify(message));
}
function decode(b64) {
  var bin = atob(b64);
  var out = new Uint8Array(bin.length);
  for (var i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
window.__akChunk = function (id, b64, last) {
  (chunks[id] = chunks[id] || []).push(decode(b64));
  if (!last) return;
  var parts = chunks[id];
  delete chunks[id];
  var size = parts.reduce(function (n, p) { return n + p.length; }, 0);
  var data = new Uint8Array(size);
  var at = 0;
  parts.forEach(function (p) { data.set(p, at); at += p.length; });
  pdfLib()
    .then(function (m) { return readPdfPages(m, data, { maxPages: ${MAX_PAGES} }); })
    .then(
      function (result) { post({ id: id, ok: true, pages: result }); },
      function (e) { post({ id: id, ok: false, error: String((e && e.message) || e).slice(0, 200) }); },
    );
};
post({ ready: true });
</script>
</body>
</html>
`;

const out = join(ROOT, 'assets', 'pdfjs', 'pdf-reader.html');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB, pdf.js ${version})`);
