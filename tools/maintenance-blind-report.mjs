#!/usr/bin/env node
/**
 * Renders docs/release/evidence/maintenance-discovery/results.json (written by the opt-in live
 * blind test, `npm run test:live -- blindMatrix`) as BLIND_RESULTS.md: the per-vehicle matrix, the
 * success metrics and the failure classes. Pure formatting — every number comes from results.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.cwd(), 'docs', 'release', 'evidence', 'maintenance-discovery');
const r = JSON.parse(readFileSync(join(dir, 'results.json'), 'utf8'));

const pct = (n, d) => (d ? `${n}/${d} (${Math.round((100 * n) / d)}%)` : '0/0');
const host = (u) => {
  try {
    return new URL(u).host;
  } catch {
    return u;
  }
};

function metrics(vehicles) {
  const blind = vehicles.filter((v) => v.id.startsWith('B'));
  const n = blind.length;
  const auto = blind.filter((v) => v.documents.length > 0).length;
  const exact = blind.filter((v) => v.documents.some((d) => d.vehicleMatch === 'exact')).length;
  const resolvedAB = (v) =>
    v.resolutions.filter((x) => x.status === 'resolved' && (x.level === 'A' || x.level === 'B'));
  const usable = blind.filter((v) => resolvedAB(v).length > 0).length;
  const il = blind.filter((v) => v.resolutions.some((x) => x.level === 'A')).length;
  const fallback = blind.filter((v) => resolvedAB(v).length === 0).length;
  const withLink = blind.filter((v) => v.userActions.length > 0).length;
  const tasks = blind.flatMap((v) => v.resolutions);
  const unresolved = tasks.filter((x) => x.status !== 'resolved' && x.status !== 'not_applicable');
  const conflicts = tasks.filter((x) => x.status === 'conflicting');
  const classes = {};
  for (const v of blind) {
    for (const c of new Set(v.failures.map((f) => f.class))) classes[c] = (classes[c] ?? 0) + 1;
  }
  return { n, auto, exact, usable, il, fallback, withLink, tasks, unresolved, conflicts, classes };
}

function vehicleRow(v) {
  const id = v.identity;
  const leads = v.discovery.flatMap((d) => d.leads);
  const blocked = v.discovery.flatMap((d) => d.blocked);
  const docs = v.documents
    .map(
      (d) =>
        `${host(d.url)} (${d.registryStatus}; match ${d.vehicleMatch}${d.unresolved.length ? `: ${d.unresolved.join(', ')} unresolved` : ''})`,
    )
    .join('; ');
  const lv = Object.entries(v.levels)
    .filter(([, c]) => c)
    .map(([k, c]) => `${k}:${c}`)
    .join(' ');
  const resolved = v.resolutions.filter((x) => x.status === 'resolved').length;
  const reqs = v.requirements?.length ?? 0;
  const cls = [...new Set(v.failures.map((f) => f.class))].join(', ') || '—';
  const detail = v.failures.map((f) => f.detail).join('; ') || '—';
  const input = resolved
    ? 'none'
    : v.userActions.length
      ? `official link offered (${v.userActions.map((a) => a.host).join(', ')}) + upload`
      : 'upload of the vehicle’s booklet';
  return `| ${v.id} | ${id.make} ${id.model} ${id.modelYear}${id.displacementCc ? ` ${id.displacementCc}cc` : ''} ${id.powertrain ?? ''} | ${leads.length} lead(s); ${blocked.length} blocked (${[...new Set(blocked.map((b) => `${host(b.url)}: ${b.reason}`))].join('; ') || '—'}) | ${docs || '—'} | ${reqs} | ${lv || '—'} | ${resolved} | ${cls} | ${detail} | ${input} |`;
}

const out = [];
out.push('# Blind maintenance-coverage results (generated)');
out.push('');
out.push(
  `Run: ${r.ranAt}. Registry entries: ${r.registryEntries}. Source: results.json (generated by`,
);
out.push(
  '`npm run test:live -- blindMatrix`; render with `node tools/maintenance-blind-report.mjs`).',
);
for (const [mode, title] of [
  ['approved', 'Production behaviour: the registry exactly as the owner approved it'],
  ['proposed', 'What-if: the PROPOSED registry hosts approved too (access policy still applies)'],
  [
    'probe',
    'Capability probe (NOT blind, NOT in the metrics): other models on the one permitted host',
  ],
]) {
  const pass = r[mode];
  if (!pass) continue;
  out.push('', `## ${title}`, '');
  out.push(
    '| # | Identity supplied | Discovery | Documents (authority status; applicability) | Requirements extracted | Evidence levels considered | Tasks scheduled | Failure class | Detail | User input needed |',
  );
  out.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const v of pass.vehicles) out.push(vehicleRow(v));
  if (mode !== 'probe') {
    const m = metrics(pass.vehicles);
    out.push('', '**Metrics (blind vehicles B1–B12 only):**', '');
    out.push(`- Automatic source discovery (≥1 official document retrieved): ${pct(m.auto, m.n)}`);
    out.push(
      `- Exact-vehicle applicability (a retrieved document proven for the exact vehicle): ${pct(m.exact, m.n)}`,
    );
    out.push(`- Usable maintenance plan (≥1 task scheduled at level A/B): ${pct(m.usable, m.n)}`);
    out.push(`- Israeli-market evidence (≥1 task at level A): ${pct(m.il, m.n)}`);
    out.push(
      `- Fallback to the user (official link and/or upload): ${pct(m.fallback, m.n)}; of which an official link was offered: ${pct(m.withLink, m.n)}`,
    );
    out.push(
      `- Unresolved / conflicting tasks: ${m.unresolved.length} / ${m.conflicts.length} of ${m.tasks.length} tasks considered`,
    );
    out.push(
      `- Failure classes (vehicles affected): ${
        Object.entries(m.classes)
          .map(([k, c]) => `${k} ${c}`)
          .join(', ') || '—'
      }`,
    );
    out.push(
      `- Knowledge reuse: catalog entries ${pass.catalogEntries}; re-runs from catalog: ${JSON.stringify(pass.reuse)}`,
    );
  } else {
    out.push('', '**Extracted requirements (probe):**', '');
    for (const v of pass.vehicles) {
      for (const q of v.requirements ?? []) {
        const i = q.interval;
        out.push(
          `- ${v.id} ${v.identity.model}: ${q.task} / ${q.action} — ${i.every ? `every ${i.every.value} ${i.every.unit}` : ''}${i.everyMonths ? ` / ${i.everyMonths} months` : ''}${i.first ? `, first at ${i.first.value}` : ''}${i.anchor ? ' (repeats from zero)' : ''}; ${q.verification}, ${q.grounded ? 'grounded' : 'NOT grounded'}, p.${q.page} ${q.locator}`,
        );
      }
    }
  }
}
writeFileSync(join(dir, 'BLIND_RESULTS.md'), `${out.join('\n')}\n`);
console.log('wrote BLIND_RESULTS.md');
