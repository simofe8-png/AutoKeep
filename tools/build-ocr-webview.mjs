#!/usr/bin/env node
/**
 * Builds assets/ocr/ocr-reader.html: the on-device booklet-photo reader (owner decision
 * 2026-10-04: photograph a booklet page → read automatically → the owner approves). One
 * self-contained offline page:
 *   - Tesseract (tesseract.js-core, Apache-2.0) with its WebAssembly inlined, loaded from a blob:
 *     URL — nothing is fetched;
 *   - the Hebrew and English models (@tesseract.js-data, Apache-2.0; 4.0.0_best_int), embedded;
 *   - a Content-Security-Policy with no network access at all (connect-src limited to blob:/data:),
 *     so a photo's content can never leave the device from this page.
 * The photo is reduced (longest side ≤ 2400 px) and turned grey before reading; the reply is the
 * same positioned-lines format as the PDF reader (y grows downwards).
 *
 * Usage: node tools/build-ocr-webview.mjs   (re-run after upgrading the OCR packages)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const coreDir = dirname(require.resolve('tesseract.js-core/package.json'));
const coreVersion = JSON.parse(readFileSync(join(coreDir, 'package.json'), 'utf8')).version;
const core = readFileSync(join(coreDir, 'tesseract-core-simd-lstm.wasm.js'), 'utf8');
const lang = (code) =>
  readFileSync(
    join(
      dirname(require.resolve(`@tesseract.js-data/${code}/package.json`)),
      '4.0.0_best_int',
      `${code}.traineddata.gz`,
    ),
  ).toString('base64');

/** A JS string literal that is safe inside an inline <script>. */
const literal = (s) =>
  JSON.stringify(s)
    .replace(/</g, '\\u003c')
    .replace(new RegExp(String.fromCharCode(0x2028), 'g'), '\\u2028')
    .replace(new RegExp(String.fromCharCode(0x2029), 'g'), '\\u2029');

const MAX_SIDE = 2400;

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval' blob:; worker-src blob:; connect-src blob: data:; img-src blob: data:">
<!-- GENERATED by tools/build-ocr-webview.mjs — do not edit by hand.
     Contains tesseract.js-core ${coreVersion} and the Hebrew / English models of @tesseract.js-data
     (Apache License 2.0, https://github.com/naptha/tesseract.js-core, https://github.com/tesseract-ocr/tessdata). -->
</head>
<body>
<script>
"use strict";
var CORE_SRC = ${literal(core)};
var MODELS = { heb: ${literal(lang('heb'))}, eng: ${literal(lang('eng'))} };
var chunks = {};
var enginePromise = null;
function post(message) {
  window.ReactNativeWebView.postMessage(JSON.stringify(message));
}
function decode(b64) {
  var bin = atob(b64);
  var out = new Uint8Array(bin.length);
  for (var i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
function gunzip(bytes) {
  var stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
  return new Response(stream).arrayBuffer().then(function (b) { return new Uint8Array(b); });
}
function engine() {
  if (!enginePromise) {
    enginePromise = new Promise(function (resolve, reject) {
      var s = document.createElement('script');
      s.src = URL.createObjectURL(new Blob([CORE_SRC], { type: 'text/javascript' }));
      s.onload = resolve;
      s.onerror = function () { reject(new Error('OCR engine failed to load')); };
      document.head.appendChild(s);
    })
      .then(function () { return TesseractCore({}); })
      .then(function (M) {
        return Promise.all(
          Object.keys(MODELS).map(function (code) {
            return gunzip(decode(MODELS[code])).then(function (raw) {
              M.FS.writeFile('./' + code + '.traineddata', raw);
            });
          }),
        ).then(function () {
          var api = new M.TessBaseAPI();
          // OEM 1 = LSTM only (the best_int models).
          if (api.Init(null, 'heb+eng', 1) !== 0) throw new Error('OCR engine failed to start');
          api.SetVariable('tessedit_pageseg_mode', '3');
          api.SetVariable('preserve_interword_spaces', '1');
          return { M: M, api: api };
        });
      });
    enginePromise.catch(function () { enginePromise = null; });
  }
  return enginePromise;
}
/** Smaller (longest side <= ${MAX_SIDE} px) and grey: faster and steadier reading of a phone photo. */
function prepare(bytes) {
  return createImageBitmap(new Blob([bytes])).then(function (bmp) {
    var scale = Math.min(1, ${MAX_SIDE} / Math.max(bmp.width, bmp.height));
    var w = Math.max(1, Math.round(bmp.width * scale));
    var h = Math.max(1, Math.round(bmp.height * scale));
    var c = document.createElement('canvas');
    c.width = w;
    c.height = h;
    var g = c.getContext('2d');
    g.drawImage(bmp, 0, 0, w, h);
    var img = g.getImageData(0, 0, w, h);
    var d = img.data;
    for (var i = 0; i < d.length; i += 4) {
      var v = Math.round(0.299 * d[i] + 0.587 * d[i + 1] + 0.114 * d[i + 2]);
      d[i] = d[i + 1] = d[i + 2] = v;
    }
    g.putImageData(img, 0, 0);
    return new Promise(function (resolve) { c.toBlob(resolve, 'image/png'); });
  }).then(function (blob) {
    return blob.arrayBuffer().then(function (b) { return new Uint8Array(b); });
  });
}
/** Tesseract TSV (word level) → positioned lines, in reading order; y grows downwards. */
function linesOf(tsv) {
  var byLine = {};
  var order = [];
  tsv.split('\\n').forEach(function (row) {
    var c = row.split('\\t');
    if (c[0] !== '5' || c.length < 12) return;
    var text = c.slice(11).join('\\t').trim();
    if (!text || Number(c[10]) < 0) return;
    var key = c[2] + ':' + c[3] + ':' + c[4];
    if (!byLine[key]) { byLine[key] = []; order.push(key); }
    byLine[key].push({ str: text, x: Number(c[6]), y: Number(c[7]), w: Number(c[8]) });
  });
  var lines = order.map(function (key) {
    var words = byLine[key];
    return {
      y: Math.min.apply(null, words.map(function (w) { return w.y; })),
      // Reading order as recognized (right to left for Hebrew); items by position.
      text: words.map(function (w) { return w.str; }).join(' '),
      items: words.slice().sort(function (a, b) { return a.x - b.x; }),
    };
  });
  lines.sort(function (a, b) { return a.y - b.y; });
  return lines;
}
window.__akChunk = function (id, b64, last) {
  (chunks[id] = chunks[id] || []).push(decode(b64));
  if (!last) return;
  var parts = chunks[id];
  delete chunks[id];
  var size = parts.reduce(function (n, p) { return n + p.length; }, 0);
  var data = new Uint8Array(size);
  var at = 0;
  parts.forEach(function (p) { data.set(p, at); at += p.length; });
  Promise.all([engine(), prepare(data)])
    .then(function (r) {
      var e = r[0];
      e.M.FS.writeFile('/input', r[1]);
      if (e.api.SetImageFile(1, 0) === 1) throw new Error('the photo could not be read');
      e.api.Recognize(null);
      var lines = linesOf(e.api.GetTSVText() || '');
      e.api.Clear();
      return [{ n: 1, lines: lines, text: lines.map(function (l) { return l.text; }).join('\\n') }];
    })
    .then(
      function (pages) { post({ id: id, ok: true, pages: pages }); },
      function (err) { post({ id: id, ok: false, error: String((err && err.message) || err).slice(0, 200) }); },
    );
};
// Start the engine at once (the models take a moment); the page is ready either way.
engine().catch(function () {});
post({ ready: true });
</script>
</body>
</html>
`;

const out = join(ROOT, 'assets', 'ocr', 'ocr-reader.html');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(
  `wrote ${out} (${(html.length / 1024).toFixed(0)} KB, tesseract.js-core ${coreVersion})`,
);
