#!/usr/bin/env node
/**
 * Builds src/features/maintenance/msource/catalogData.ts from the worker host's class-level
 * M-SOURCE results (docs/maintenance/data/msource/*-catalog.json). Structured evidence and
 * provenance only; the files themselves contain no document bytes.
 *
 * Usage: node tools/build-msource-catalog.mjs
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const dir = join(root, 'docs', 'maintenance', 'data', 'msource');
const entries = readdirSync(dir)
  .filter((f) => f.endsWith('-catalog.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
  .filter((c) => c.sources.length > 0);
// Changes whenever the bundled results change: a vehicle whose last search found nothing is searched
// again automatically when the catalog it was searched against is outdated.
const version = createHash('sha256')
  .update(JSON.stringify(entries.map((e) => [e.classKey, e.runId, e.sources.length])))
  .digest('hex')
  .slice(0, 16);
const out = `
// GENERATED by tools/build-msource-catalog.mjs — do not edit by hand.
// Class-level M-SOURCE results from the worker host (structured evidence + provenance only).
/** Version of the bundled catalog (hash of its classes and runs). */
export const MSOURCE_CATALOG_VERSION = '${version}';

export const MSOURCE_CATALOG: readonly {
  classKey: string;
  runId: string;
  sources: readonly { canonicalUrl: string; value: unknown }[];
}[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, 'src', 'features', 'maintenance', 'msource', 'catalogData.ts'), out);
console.log(
  `${entries.length} vehicle classes, ${entries.reduce((n, e) => n + e.sources.length, 0)} sources`,
);
